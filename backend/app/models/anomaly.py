"""SQLAlchemy ORM model for anomaly detection results."""

import enum
from datetime import datetime
from typing import Any, Dict, Optional

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Index,
    String,
    func,
)
from sqlalchemy.dialects.mysql import JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base


class DetectorTypeEnum(str, enum.Enum):
    """Detection engine type that produced the verdict."""

    DFA = "DFA"
    ISOLATION_FOREST = "ISOLATION_FOREST"
    HYBRID = "HYBRID"


class AnomalySeverityEnum(str, enum.Enum):
    """Severity classification of detected anomalies."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AnomalyResult(Base):
    """Detection verdicts generated by DFA, Isolation Forest, or Hybrid Engine."""

    __tablename__ = "anomaly_results"
    __table_args__ = (
        Index("idx_anomaly_case", "case_id"),
        Index("idx_anomaly_severity", "severity"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    case_id: Mapped[str] = mapped_column(
        String(64),
        ForeignKey("process_cases.case_id", ondelete="CASCADE"),
        nullable=False,
    )
    event_log_id: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        ForeignKey("event_logs.id", ondelete="CASCADE"),
        nullable=True,
    )
    detector_type: Mapped[DetectorTypeEnum] = mapped_column(
        Enum(DetectorTypeEnum, name="detector_type_enum"),
        nullable=False,
    )
    is_anomaly: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    anomaly_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    anomaly_reason: Mapped[str] = mapped_column(String(255), nullable=False)
    severity: Mapped[AnomalySeverityEnum] = mapped_column(
        Enum(AnomalySeverityEnum, name="anomaly_severity_enum"),
        nullable=False,
    )
    rule_violation: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    detected_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, server_default=func.current_timestamp()
    )
    details_json: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationships
    case: Mapped["ProcessCase"] = relationship("ProcessCase", back_populates="anomalies")  # type: ignore # noqa: F821
    event_log: Mapped[Optional["EventLog"]] = relationship(  # type: ignore # noqa: F821
        "EventLog",
        back_populates="anomalies",
    )

    def __repr__(self) -> str:
        return (
            f"<AnomalyResult(id={self.id}, case='{self.case_id}', "
            f"detector='{self.detector_type}', severity='{self.severity}')>"
        )
